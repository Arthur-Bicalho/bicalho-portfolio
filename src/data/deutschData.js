// Índice da palavra do dia: dias desde 1970 no fuso de Brasília
export function indiceDoDia(agora = new Date(), total = palavras.length) {
  const [ano, mes, dia] = new Intl.DateTimeFormat("en-CA", { timeZone: "America/Sao_Paulo" })
    .format(agora)
    .split("-")
    .map(Number);
  const dias = Math.floor(Date.UTC(ano, mes - 1, dia) / 864e5);
  return dias % total;
}
